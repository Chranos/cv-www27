def colspec_count(spec):
    s = re.sub(r'@\{[^{}]*\}', '', spec)
    s = re.sub(r'[pmb]\{[^{}]*\}', 'p', s)
    s = re.sub(r'\s+', '', s)
    for ch in s:
        if ch not in 'lrcp|':
            raise SystemExit('unparsed colspec char ' + repr(ch) + ' in ' + spec)
    return sum(1 for ch in s if ch in 'lrcp')


def split_cells(row):
    cells, depth, cur, i = [], 0, '', 0
    while i < len(row):
        c = row[i]
        if c == '\\' and i + 1 < len(row):
            cur += row[i:i+2]; i += 2; continue
        if c == '{': depth += 1
        elif c == '}': depth -= 1
        if c == '&' and depth == 0:
            cells.append(cur); cur = ''
        else:
            cur += c
        i += 1
    cells.append(cur)
    return cells


MC = re.compile(r'^\s*\\multicolumn\{(\d+)\}')


def tabular(text):
    m = re.search(r'\\begin\{tabular\}\{((?:[^{}]|\{[^{}]*\})*)\}\n(.*?)\\end\{tabular\}', text, re.S)
    spec, body = m.group(1), m.group(2)
    rows = []
    for line in body.split('\n'):
        t = line.strip()
        if not t or t in ('\\toprule', '\\midrule', '\\bottomrule'):
            continue
        if not t.endswith('\\\\'):
            raise SystemExit('unexpected non-row line in tabular: ' + t[:80])
        rows.append(t[:-2].rstrip())
    return spec, rows


def structure(name, text):
    spec, rows = tabular(text)
    ncol = colspec_count(spec)
    bad = []
    for r in rows:
        used = 0
        for c in split_cells(r):
            m = MC.match(c)
            used += int(m.group(1)) if m else 1
        if used != ncol:
            bad.append({'row': r.split('&')[0].strip()[:60], 'consumes': used, 'spec': ncol})
    return ncol, len(rows), bad


